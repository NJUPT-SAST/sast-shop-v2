BEGIN;

ALTER TABLE catalog.catalog_store
-- 当前是否可以对 C 端展示。allowed 正常，blocked 被人为下架。default 'allowed' 让存量几万条数据一次性合规，迁移不阻塞业务
    ADD COLUMN moderation_status TEXT NOT NULL DEFAULT 'allowed' CHECK (moderation_status IN ('allowed', 'blocked')),
     -- 屏蔽原因，是给商家看的文案，会出现在商家后台的违规提示里，用于申诉沟通
    ADD COLUMN moderation_reason TEXT NOT NULL DEFAULT '',
 -- 执行这次判定的管理员 user_id，可空
    ADD COLUMN moderation_by BIGINT,
       -- 判定时间，timestamptz 带时区，跨时区后台不会错位，可空
    ADD COLUMN moderation_at TIMESTAMPTZ;


ALTER TABLE catalog.catalog_product_template

    ADD COLUMN moderation_status TEXT NOT NULL DEFAULT 'allowed' CHECK (moderation_status IN ('allowed', 'blocked')),
    ADD COLUMN moderation_reason TEXT NOT NULL DEFAULT '',
    ADD COLUMN moderation_by BIGINT,
    ADD COLUMN moderation_at TIMESTAMPTZ;

ALTER TABLE spot.spot_goods

    ADD COLUMN moderation_status TEXT NOT NULL DEFAULT 'allowed' CHECK (moderation_status IN ('allowed', 'blocked')),
    ADD COLUMN moderation_reason TEXT NOT NULL DEFAULT '',
    ADD COLUMN moderation_by BIGINT,
    ADD COLUMN moderation_at TIMESTAMPTZ;

CREATE INDEX idx_catalog_store_admin ON catalog.catalog_store (moderation_status, id DESC);
CREATE INDEX idx_catalog_template_admin ON catalog.catalog_product_template (moderation_status, store_id, id DESC);
CREATE INDEX idx_spot_goods_admin ON spot.spot_goods (moderation_status, seller_id, id DESC);
CREATE INDEX idx_spot_order_admin ON spot.spot_order (status, created_at DESC, id DESC);

CREATE TABLE catalog.admin_action_log (
    -- 允许手工插指定 id，方便从旧系统导入历史日志或做数据回放
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    --故意不加外键——审计记录必须独立于用户表存活，管理员账号注销了，他当年封的店也不能变成无主
    actor_id bigint NOT NULL,
    -- 动作类型，用 text 而非 enum，新增动作不用改表结构
    action text NOT NULL,
    -- 目标对象类型
    target_type text NOT NULL,
    -- 目标对象主键。和 target_type 组成多态外键（PG 无法对多态关系建真外键，只能在应用层校验）
    target_id bigint NOT NULL,
    -- 前端/网关生成的请求唯一 id。一箭双雕：既做幂等键，也用来把"一次操作写下的多条日志"串成一组（比如屏蔽商品同时冻结了店铺）
    request_id text NOT NULL,

    reason text NOT NULL,
    evidence text NOT NULL DEFAULT '',
    before_state jsonb NOT NULL,
    after_state jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON catalog.admin_action_log (created_at DESC, id DESC);
CREATE INDEX ON catalog.admin_action_log (target_type, target_id, id DESC);

CREATE TABLE catalog.admin_request_dedup (
    actor_id bigint NOT NULL,
    action text NOT NULL,
    request_id text NOT NULL,
    input_hash char(64) NOT NULL,
    response jsonb NOT NULL DEFAULT 'null',
    completed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (actor_id, action, request_id)
);


CREATE TABLE spot.admin_action_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint NOT NULL,
    action text NOT NULL,
    target_type text NOT NULL,
    target_id bigint NOT NULL,
    request_id text NOT NULL,
    reason text NOT NULL,
    evidence text NOT NULL DEFAULT '',
    before_state jsonb NOT NULL,
    after_state jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON spot.admin_action_log (created_at DESC, id DESC);
CREATE INDEX ON spot.admin_action_log (target_type, target_id, id DESC);
-- 幂等锁
CREATE TABLE spot.admin_request_dedup (
    -- 同一个人 + 同一个动作 + 同一个请求 id，全局只能存在一行
    actor_id bigint NOT NULL,
    action text NOT NULL,
    request_id text NOT NULL,
     -- 入参的 SHA-256。防止同一个 request_id 被拿去发不同内容的请求（前端 bug 复用 id，或有人重放）
    input_hash char(64) NOT NULL,
    -- 首次执行的响应缓存。重复请求不再跑业务逻辑，直接返回它。注意 'null' 是 JSON 的 null，不是 SQL NULL，所以能配合 NOT NULL
    response jsonb NOT NULL DEFAULT 'null',
    -- 是否执行完。false 有两种含义：正在执行中，或执行到一半进程崩了——后者是排查"悬挂请求"的抓手
    completed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (actor_id, action, request_id)
);


COMMIT;
