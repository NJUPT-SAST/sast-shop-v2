--给user_account增加认证版本字段
-- 用户登录后，签发的令牌带上当时的auth-version,后端每次校验令牌时除了签名还比较令牌和数据库里该用户的authVersion，如果两者不一致，说明用户的角色和状态已经变化，作废旧令牌，要求重新登录或重新认证
ALTER TABLE "user".user_account ADD COLUMN auth_version bigint NOT NULL DEFAULT 1 CHECK (auth_version > 0);
--认证版本自动推进函数与触发器
CREATE FUNCTION "user".advance_auth_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.role IS DISTINCT FROM OLD.role OR NEW.status IS DISTINCT FROM OLD.status THEN
        NEW.auth_version := GREATEST(NEW.auth_version, OLD.auth_version + 1);
    END IF;
    IF NEW.auth_version < OLD.auth_version THEN
        RAISE EXCEPTION 'authentication version cannot decrease';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER advance_auth_version BEFORE UPDATE ON "user".user_account
    FOR EACH ROW EXECUTE FUNCTION "user".advance_auth_version();
