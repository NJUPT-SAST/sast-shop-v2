BEGIN;

CREATE TABLE catalog.catalog_product_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES catalog.catalog_store(id) ON DELETE RESTRICT,
    parent_id BIGINT,
    name TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT catalog_product_category_store_id_id_key UNIQUE (store_id, id),
    CONSTRAINT catalog_product_category_parent_same_store_fk
        FOREIGN KEY (store_id, parent_id)
        REFERENCES catalog.catalog_product_category(store_id, id)
        ON DELETE RESTRICT,
    CONSTRAINT catalog_product_category_parent_not_self CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT catalog_product_category_name_nonempty CHECK (btrim(name) <> ''),
    CONSTRAINT catalog_product_category_name_length CHECK (char_length(btrim(name)) BETWEEN 1 AND 50)
);

CREATE UNIQUE INDEX catalog_product_category_root_name_key
    ON catalog.catalog_product_category (store_id, lower(btrim(name)))
    WHERE parent_id IS NULL;
CREATE UNIQUE INDEX catalog_product_category_child_name_key
    ON catalog.catalog_product_category (store_id, parent_id, lower(btrim(name)))
    WHERE parent_id IS NOT NULL;
CREATE INDEX catalog_product_category_tree_idx
    ON catalog.catalog_product_category (store_id, parent_id, sort_order, id);

ALTER TABLE catalog.catalog_product_template
    ADD COLUMN category_id BIGINT;
ALTER TABLE catalog.catalog_product_template
    ADD CONSTRAINT catalog_product_template_store_category_fk
        FOREIGN KEY (store_id, category_id)
        REFERENCES catalog.catalog_product_category(store_id, id)
        ON DELETE RESTRICT;
CREATE INDEX catalog_product_template_store_category_idx
    ON catalog.catalog_product_template (store_id, category_id, id);

COMMIT;
